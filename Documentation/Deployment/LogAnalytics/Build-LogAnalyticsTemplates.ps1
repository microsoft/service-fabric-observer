#Requires -Version 7.0
<#
.SYNOPSIS
Generates the FabricObserver and ClusterObserver Log Analytics (Logs Ingestion API) ARM templates from LogAnalyticsSchema.json.

.DESCRIPTION
Each generated template deploys a data collection rule (DCR) that maps the JSON records sent by Observer into the
same columns and types that the Data Collector API created. It either creates the destination table or adds any missing
standard columns to an existing (already converted) table while keeping its other columns. It also creates or reuses
the user-assigned managed identity that sends the data, and grants that identity permission to send through the DCR.

Run without parameters to regenerate the templates. Use -Check to verify that the committed templates are current.

.PARAMETER Check
Compares the generated output with the files on disk and fails if they differ. Writes nothing.
#>
[CmdletBinding()]
param([switch] $Check)

$ErrorActionPreference = 'Stop'
$schema = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'LogAnalyticsSchema.json') -Raw | ConvertFrom-Json
$typeBySuffix = [ordered]@{ s = 'string'; d = 'real'; b = 'boolean'; t = 'datetime'; g = 'guid' }
$publisherRoleId = '3913510d-42f4-4e42-8a64-420c390055eb' # Monitoring Metrics Publisher

function Get-ColumnExpression([string] $Name, [string[]] $AllNames) {
    if ($Name -cnotmatch '^(.+)_([sdbtg])$') { throw "Column '$Name' has no Data Collector type suffix." }
    $field = $Matches[1]
    $suffix = $Matches[2]
    # Data Collector flattens nested objects with '_' (NodeDeactivationInfo_Status_d).
    $path = 'Payload' + (($field -split '_' | ForEach-Object { "['$_']" }) -join '')
    $siblings = @($AllNames | Where-Object { $_ -cmatch ('^' + [regex]::Escape($field) + '_[sdbtg]$') } |
        ForEach-Object { $_.Substring($_.Length - 1) })
    switch ($suffix) {
        'd' { return "iff(gettype($path) in ('long','real','int'), todouble($path), real(null))" }
        'b' { return "iff(gettype($path) == 'bool', tobool($path), bool(null))" }
        't' { return "todatetime($path)" }
        'g' { return "toguid(tostring($path))" }
        's' {
            # When the Data Collector API stored a value in a typed sibling column, the _s column stays empty.
            $guards = @()
            if ('g' -cin $siblings) { $guards += "isnull(toguid(tostring($path)))" }
            if ('t' -cin $siblings) { $guards += "isnull(todatetime($path))" }
            if ('d' -cin $siblings) { $guards += "gettype($path) !in ('long','real','int')" }
            if ('b' -cin $siblings) { $guards += "gettype($path) != 'bool'" }
            if ($AllNames -cmatch ('^' + [regex]::Escape($field) + '_.+_[sdbtg]$')) { $guards += "gettype($path) != 'dictionary'" }
            if ($guards.Count) { return "iff($($guards -join ' and '), tostring($path), '')" }
            return "tostring($path)"
        }
    }
}

function New-Template([string] $Application, [object[]] $Columns) {
    foreach ($column in $Columns) {
        if ($column.name -cnotmatch '_([sdbtg])$' -or $typeBySuffix[$Matches[1]] -ne $column.type) {
            throw "$Application column '$($column.name)' type '$($column.type)' does not match its suffix."
        }
    }
    $names = @($Columns.name)
    $projections = @(
        'TimeGenerated = now()', "SourceSystem = 'RestAPI'", 'MG = guid(null)',
        "ManagementGroupName = ''", "Computer = ''", "RawData = ''") +
        @($names | ForEach-Object { "$_ = $(Get-ColumnExpression $_ $names)" })
    $transform = "source`n| project`n    " + ($projections -join ",`n    ")
    $standardColumns = @($schema.standardColumns | ForEach-Object { [ordered]@{ name = $_.name; type = $_.type } })
    $recordColumns = @($Columns | ForEach-Object { [ordered]@{ name = $_.name; type = $_.type } })
    $tableId = "resourceId('Microsoft.OperationalInsights/workspaces/tables', parameters('workspaceName'), parameters('tableName'))"
    $columnsDeployment = "take(format('{0}-columns', parameters('tableName')), 64)"

    $dcrId = "[resourceId('Microsoft.Insights/dataCollectionRules', parameters('dcrName'))]"
    [ordered]@{
        '$schema' = 'https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#'
        contentVersion = '1.0.0.0'
        metadata = [ordered]@{
            description = "Logs Ingestion API resources for $Application. Generated by Build-LogAnalyticsTemplates.ps1; do not edit by hand."
        }
        parameters = [ordered]@{
            workspaceName = [ordered]@{ type = 'string'; metadata = [ordered]@{ description = 'Existing Log Analytics workspace in this resource group.' } }
            tableName = [ordered]@{ type = 'string'; metadata = [ordered]@{ description = 'Destination custom table name, ending in _CL.' } }
            createTable = [ordered]@{ type = 'bool'; metadata = [ordered]@{ description = 'true: create a new table (fresh setup or dual write). The name must not be an existing table. false: send to an existing table (single write). The table must already be converted to a DCR-based table; missing standard columns are added and existing columns are kept.' } }
            dcrName = [ordered]@{ type = 'string'; defaultValue = "dcr-$($Application.ToLowerInvariant())"; metadata = [ordered]@{ description = 'Name of the data collection rule to create or update.' } }
            location = [ordered]@{ type = 'string'; defaultValue = '[resourceGroup().location]'; metadata = [ordered]@{ description = 'Region of the data collection rule. Must be the workspace region.' } }
            dataCollectionEndpointResourceId = [ordered]@{ type = 'string'; defaultValue = ''; metadata = [ordered]@{ description = 'Optional data collection endpoint resource ID (required for Private Link). Empty: the DCR provides its own ingestion endpoint.' } }
            existingManagedIdentityResourceId = [ordered]@{ type = 'string'; defaultValue = ''; metadata = [ordered]@{ description = 'Optional resource ID of an existing user-assigned managed identity (any resource group or subscription). Empty: create or reuse the identity named by managedIdentityName in this resource group.' } }
            managedIdentityName = [ordered]@{ type = 'string'; defaultValue = 'id-observer-loganalytics'; metadata = [ordered]@{ description = 'User-assigned managed identity to create or reuse in this resource group. Use the same name for FabricObserver and ClusterObserver so both share one identity. Ignored when existingManagedIdentityResourceId is set.' } }
            grantPublisherRole = [ordered]@{ type = 'bool'; defaultValue = $true; metadata = [ordered]@{ description = 'true: grant the identity Monitoring Metrics Publisher on the DCR (the deployer needs permission to assign roles, such as Owner or User Access Administrator). false: grant it separately.' } }
        }
        variables = [ordered]@{
            standardColumns = $standardColumns
            recordColumns = $recordColumns
            transformKql = $transform
            identityId = "[if(empty(parameters('existingManagedIdentityResourceId')), resourceId('Microsoft.ManagedIdentity/userAssignedIdentities', parameters('managedIdentityName')), parameters('existingManagedIdentityResourceId'))]"
        }
        resources = @(
            [ordered]@{
                condition = "[empty(parameters('existingManagedIdentityResourceId'))]"
                type = 'Microsoft.ManagedIdentity/userAssignedIdentities'
                apiVersion = '2023-01-31'
                name = "[parameters('managedIdentityName')]"
                location = "[parameters('location')]"
            },
            [ordered]@{
                condition = "[parameters('createTable')]"
                type = 'Microsoft.OperationalInsights/workspaces/tables'
                apiVersion = '2022-10-01'
                name = "[format('{0}/{1}', parameters('workspaceName'), parameters('tableName'))]"
                properties = [ordered]@{
                    plan = 'Analytics'
                    schema = [ordered]@{ name = "[parameters('tableName')]"; columns = "[concat(variables('standardColumns'), variables('recordColumns'))]" }
                }
            },
            # Existing table: a table update replaces the column list, so send the current columns plus the missing
            # record columns. Built-in columns (TimeGenerated, SourceSystem, MG, ...) must not be listed.
            # A nested deployment is needed so the existing columns are read before the update.
            [ordered]@{
                condition = "[not(parameters('createTable'))]"
                type = 'Microsoft.Resources/deployments'
                apiVersion = '2022-09-01'
                name = "[$columnsDeployment]"
                properties = [ordered]@{
                    mode = 'Incremental'
                    expressionEvaluationOptions = [ordered]@{ scope = 'inner' }
                    parameters = [ordered]@{
                        workspaceName = [ordered]@{ value = "[parameters('workspaceName')]" }
                        tableName = [ordered]@{ value = "[parameters('tableName')]" }
                        columns = [ordered]@{ value = "[union(map(reference($tableId, '2022-10-01').schema.columns, lambda('c', createObject('name', lambdaVariables('c').name, 'type', lambdaVariables('c').type))), variables('recordColumns'))]" }
                    }
                    template = [ordered]@{
                        '$schema' = 'https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#'
                        contentVersion = '1.0.0.0'
                        parameters = [ordered]@{
                            workspaceName = [ordered]@{ type = 'string' }
                            tableName = [ordered]@{ type = 'string' }
                            columns = [ordered]@{ type = 'array' }
                        }
                        resources = @([ordered]@{
                            type = 'Microsoft.OperationalInsights/workspaces/tables'
                            apiVersion = '2022-10-01'
                            name = "[format('{0}/{1}', parameters('workspaceName'), parameters('tableName'))]"
                            properties = [ordered]@{
                                plan = 'Analytics'
                                schema = [ordered]@{ name = "[parameters('tableName')]"; columns = "[parameters('columns')]" }
                            }
                        })
                    }
                }
            },
            [ordered]@{
                type = 'Microsoft.Insights/dataCollectionRules'
                apiVersion = '2023-03-11'
                name = "[parameters('dcrName')]"
                location = "[parameters('location')]"
                kind = "[if(empty(parameters('dataCollectionEndpointResourceId')), 'Direct', json('null'))]"
                dependsOn = @("[$tableId]", "[resourceId('Microsoft.Resources/deployments', $columnsDeployment)]")
                properties = [ordered]@{
                    dataCollectionEndpointId = "[if(empty(parameters('dataCollectionEndpointResourceId')), json('null'), parameters('dataCollectionEndpointResourceId'))]"
                    streamDeclarations = [ordered]@{
                        "Custom-$Application" = [ordered]@{ columns = @([ordered]@{ name = 'Payload'; type = 'dynamic' }) }
                    }
                    destinations = [ordered]@{
                        logAnalytics = @([ordered]@{
                            name = 'workspace'
                            workspaceResourceId = "[resourceId('Microsoft.OperationalInsights/workspaces', parameters('workspaceName'))]"
                        })
                    }
                    dataFlows = @([ordered]@{
                        streams = @("Custom-$Application")
                        destinations = @('workspace')
                        transformKql = "[variables('transformKql')]"
                        outputStream = "[format('Custom-{0}', parameters('tableName'))]"
                    })
                }
            },
            [ordered]@{
                condition = "[parameters('grantPublisherRole')]"
                type = 'Microsoft.Authorization/roleAssignments'
                apiVersion = '2022-04-01'
                scope = $dcrId
                name = "[guid($($dcrId.Trim('[', ']')), variables('identityId'), '$publisherRoleId')]"
                dependsOn = @($dcrId, "[resourceId('Microsoft.ManagedIdentity/userAssignedIdentities', parameters('managedIdentityName'))]")
                properties = [ordered]@{
                    roleDefinitionId = "[subscriptionResourceId('Microsoft.Authorization/roleDefinitions', '$publisherRoleId')]"
                    principalId = "[reference(variables('identityId'), '2023-01-31').principalId]"
                    # Lets the grant succeed before a newly created identity has replicated in Microsoft Entra ID.
                    principalType = 'ServicePrincipal'
                }
            }
        )
        # LogAnalytics* output names match the application parameters they supply.
        outputs = [ordered]@{
            ManagedIdentityResourceId = [ordered]@{ type = 'string'; value = "[variables('identityId')]" }
            LogAnalyticsIngestionEndpoint = [ordered]@{ type = 'string'; value = "[if(empty(parameters('dataCollectionEndpointResourceId')), reference($($dcrId.Trim('[', ']')), '2023-03-11').endpoints.logsIngestion, reference(parameters('dataCollectionEndpointResourceId'), '2023-03-11').logsIngestion.endpoint)]" }
            LogAnalyticsDcrImmutableId = [ordered]@{ type = 'string'; value = "[reference($($dcrId.Trim('[', ']')), '2023-03-11').immutableId]" }
            LogAnalyticsStreamName = [ordered]@{ type = 'string'; value = "Custom-$Application" }
            LogAnalyticsManagedIdentityClientId = [ordered]@{ type = 'string'; value = "[reference(variables('identityId'), '2023-01-31').clientId]" }
        }
    }
}

$stale = @()
foreach ($application in $schema.applications.PSObject.Properties) {
    $template = New-Template $application.Name @($application.Value)
    $text = (($template | ConvertTo-Json -Depth 30) -replace '\r?\n', "`r`n") + "`r`n"
    $path = Join-Path $PSScriptRoot "$($application.Name).LogAnalytics.json"
    if ($Check) {
        if (-not (Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path) -cne $text) { $stale += $path }
        continue
    }
    [IO.File]::WriteAllText($path, $text, [Text.UTF8Encoding]::new($false))
    Write-Output "$($application.Name): $($application.Value.Count) record columns -> $path"
}
if ($stale) { throw "Templates are out of date; run Build-LogAnalyticsTemplates.ps1: $($stale -join ', ')" }
